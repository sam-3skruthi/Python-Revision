a = 5
b = 3

#arithmetic operators
print(a+b)
print(a-b)
print(a*b)
print(a/b)
print(a%b)
print(a//b)
print(a**b)

#comparison opertors
print(a==b)
print(a!=b)
print(a>b)
print(a<b)

#logical operators
print(a>2 and a<20)
print(a>2 or a<20)
print(not(a>0))

#assignment operators
a = 5
a += 3
print(a)